function text_of(container: HTMLElement) {
  return container.textContent ?? ''
}

function positions(text: string, parts: string[]) {
  let from = 0
  return parts.map((part) => {
    const at = text.indexOf(part, from)
    expect(at, `"${part}" comes next in the text`).toBeGreaterThanOrEqual(0)
    from = at + part.length
    return at
  })
}

