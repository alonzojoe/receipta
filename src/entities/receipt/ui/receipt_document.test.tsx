describe('ReceiptDocument: footer (criteria 13, 14)', () => {
  it('is Generated by and the light wordmark, linked to the app, with no timestamp', () => {
    const { container } = render(<ReceiptDocument view={make_view()} />)
    const footer = container.querySelector('.receipt-footer') as HTMLElement
    expect(footer.textContent).toContain('Generated by')
    expect([...footer.querySelectorAll('img')].map((img) => img.getAttribute('src'))).toEqual([
      logo_mark_src,
      wordmark_light_src,
    ])
    // The two are one lockup, so they share a parent and sit closer to each other than to
    // the label.
    const lockup = footer.querySelector('.receipt-footer-lockup') as HTMLElement
    expect([...lockup.children].map((el) => el.className)).toEqual([
      'receipt-footer-mark',
      'receipt-footer-wordmark',
    ])
    // Two links, both to the app and nowhere else: the credit on the left and the printed
    // address on the right. Both open away from whatever page is showing the receipt and
    // carry no referrer, because a receipt is a file that gets forwarded.
    const links = [...container.querySelectorAll('a')] as HTMLAnchorElement[]
    expect(links).toHaveLength(2)
    for (const link of links) {
      expect(link).toHaveAttribute('href', site.url)
      expect(link).toHaveAttribute('target', '_blank')
      expect(link.rel).toContain('noreferrer')
    }

    const [credit, address] = links
    expect(credit.textContent).toContain('Generated by')
    // The address is printed, not only linked: in the exports the anchor is dead pixels,
    // so the text is the only way a reader gets here.
    // Printed with its scheme, as the author asked: in an export this text is the whole
    // address a reader has to type.
    expect(address.textContent).toBe(site.url)
    expect(address.textContent).toContain('https://')
    // The label size, 13px - the document's floor, one step below the body text beside it.
    expect(address.className).toContain('receipt-label')
    expect(text_of(container)).not.toMatch(/\d{1,2}:\d{2}/)
    expect(footer.querySelector('img')?.getAttribute('loading')).toBe('eager')
  })

  /**
   * The underline is not decoration. Both exports are rasterised, so the anchor becomes
   * pixels and the text is the only way a reader gets to the app - an underline is what
   * tells them it is an address rather than a stray phrase.
   */
  it('underlines the printed address, since in an export it is only text', () => {
    const url_rule = receipt_css.match(/\.receipt-footer-url\s*\{([^}]*)\}/)?.[1] ?? ''
    expect(url_rule).toMatch(/text-decoration:\s*underline/)
  })

  it('keeps the page label under the address, not beside it', () => {
    const { container } = render(<ReceiptDocument view={make_view()} />)
    const right = container.querySelector('.receipt-footer-right') as HTMLElement

    expect(right.querySelector('.receipt-footer-url')).not.toBeNull()
    const rule = receipt_css.match(/\.receipt-footer-right\s*\{([^}]*)\}/)?.[1] ?? ''
    expect(rule).toMatch(/flex-direction:\s*column/)
    expect(rule).toMatch(/align-items:\s*flex-end/)
  })

  it('names the wordmark Receipta once, for a reader of the markup', () => {
    const { container } = render(<ReceiptDocument view={make_view()} />)
    expect(within(container).getAllByAltText('Receipta')).toHaveLength(1)
  })

  it('keeps both logos in the footer, and both waited on before rasterising', () => {
    const { container } = render(<ReceiptDocument view={make_view()} />)
    expect([...container.querySelectorAll('img[data-logo="receipta"]')].map((img) => img.getAttribute('src'))).toEqual([
      logo_mark_src,
      wordmark_light_src,
    ])
  })
})

