import { long_date } from './long_date'
import { normalise_notes } from './notes'
import { group_quantity } from './quantity_text'
import { payment_method_icon, payment_method_name } from './payment_method'
import { cash_method, type ReceiptInput } from './receipt_input'
import { item_figures, summarise_receipt } from './receipt_totals'

/** The one sentence the document always carries. No input and no prop removes it. */
export const receipt_statement = 'This is a proof of payment.'

/** Captions, in the words the spec fixes. They are not data, so they are not in the view. */
export const receipt_labels = {
  title: 'Receipt',
  receipt_no: 'Receipt number',
  issued_by: 'Issued by',
  issued_to: 'Issued to',
  description: 'Description',
  qty: 'Qty',
  unit_price: 'Unit price',
  amount: 'Amount',
  subtotal: 'Subtotal',
  discount: 'Discount',
  total: 'Total',
  amount_paid: 'Amount paid',
  payment: 'Payment',
  payment_method: 'Payment method',
  date: 'Date',
  reference_no: 'Reference number',
  notes: 'Notes',
  generated_by: 'Generated by',
} as const

export type ItemView = {
  name: string
  /** `1.5`, `9,999.999`. Empty while the line's numbers are not valid. */
  quantity: string
  /** `₱150.00`. Empty while the line's numbers are not valid. */
  unit_price: string
  /** The line amount. Empty while the line's numbers are not valid. */
  amount: string
  image: string | null
}

export type TotalsView = {
  /** Present only with a discount above 0. */
  subtotal: string | null
  /** `-₱50.00`, with an ASCII hyphen-minus. Present only with a discount above 0. */
  discount: string | null
  /**
   * `Discount` or `Discount (student)`. Built here rather than in the component so the
   * document prints a string it was handed, and so one test over the view covers both the
   * preview and both exports.
   */
  discount_label: string
  total: string
}

export type PaymentView = {
  name: string
  /** A local logo path, or null (Cash, Other). */
  icon: string | null
  /** Present only when typed and the method is not Cash. */
  reference: string | null
}

/** Every string the document shows, built once. The components only lay it out. */
export type ReceiptView = {
  receipt_no: string
  date: string
  issuer: string
  recipient: string
  /** `₱1,234.56 paid on 16 October 2026`. Null while the total is not valid. */
  paid_line: string | null
  items: readonly ItemView[]
  has_images: boolean
  totals: TotalsView
  payment: PaymentView
  /** Normalised text, or null when empty. */
  notes: string | null
  statement: string
}

function money_or_empty(centavos: number | undefined) {
  return centavos === undefined ? '' : format_centavos(centavos)
}

/**
 * The form's values, turned into the document's text. The money comes from the same
 * functions the form uses (`summarise_receipt`, `item_figures`) and the one formatter.
 * This file does no arithmetic and no formatting of its own, so the document cannot
 * disagree with the form to the centavo.
 *
 * Party type is not an input here, so Individual and Organization cannot differ.
 */
/**
 * `Discount (student)` when a reason was given, `Discount` when not. Collapses inner
 * whitespace so a pasted reason cannot print as `Discount (student    card)`.
 *
 * The reason is wrapped in Unicode isolates (U+2068 / U+2069). Without them a
 * right-to-left phrase reorders the surrounding punctuation and the closing parenthesis
 * lands on the wrong side of the label. They are invisible and carry through to both
 * exports, since the document prints this string as it is given.
 */
function discount_label(description: string) {
  const reason = description.trim().replace(/\s+/g, ' ')
  return reason === '' ? receipt_labels.discount : `${receipt_labels.discount} (\u2068${reason}\u2069)`
}

export function build_receipt_view(input: ReceiptInput): ReceiptView {
  const summary = summarise_receipt(input)
  const has_discount = summary.discount !== undefined && summary.discount > 0
  const notes = normalise_notes(input.notes)
  const reference = input.reference_no.trim()
  const shows_reference = reference !== '' && input.payment_method !== cash_method
  const icon = payment_method_icon(input.payment_method)

  return {
    receipt_no: input.receipt_no,
    date: long_date(input.receipt_date),
    issuer: input.issuer_name.trim(),
    recipient: input.recipient_name.trim(),
    paid_line: summary.total === undefined ? null : `${format_centavos(summary.total)} paid on ${long_date(input.receipt_date)}`,
    items: input.items.map((item) => {
      const figures = item_figures(item)
      return {
        name: item.name.trim(),
        quantity: figures ? group_quantity(figures.quantity) : '',
        unit_price: figures ? format_centavos(figures.unit_price) : '',
        amount: figures ? format_centavos(figures.line_total) : '',
        image: item.image,
      }
    }),
    has_images: input.items.some((item) => item.image !== null),
    totals: {
      subtotal: has_discount ? format_centavos(summary.subtotal) : null,
      discount: has_discount ? `-${money_or_empty(summary.discount)}` : null,
      discount_label: discount_label(input.discount_description),
      total: money_or_empty(summary.total),
    },
    payment: {
      name: payment_method_name(input.payment_method, input.other_method),
      icon: icon ?? null,
      reference: shows_reference ? reference : null,
    },
    notes: notes === '' ? null : notes,
    statement: receipt_statement,
  }
}
